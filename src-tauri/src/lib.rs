//! DSHWAR 桌面壳的**宿主能力** —— 三个宿主里只有这一个有的东西。
//!
//! # 边界:本 crate 不含业务逻辑
//!
//! 「一份 React 三宿主」意味着业务逻辑全在 TS 里,三处共用。
//! 这个 crate 只提供 TS 侧做不到的三件事:
//!
//! | 模块 | 它做什么 | 为什么必须在这里 |
//! | --- | --- | --- |
//! | [`keychain`] | 系统钥匙串读写 | 访问控制要由操作系统做,而那要在被签名的二进制里 |
//! | [`allowlist`] | 跨源允许清单 | 前端是 `tauri://localhost`,网关是 `127.0.0.1:<port>` —— 真跨源 |
//!
//! # ⚠️ 它**不是**一个完整的 Tauri app
//!
//! 打包(Node 22 运行时 + `node-pty` / `sharp` / `@vscode/ripgrep` 三个原生模块)
//! 是**单独两周**,不进本 Session。一个完整的 app crate 要跑 `tauri-build` 的
//! codegen,那一步要前端产物、要图标、要签名配置 —— 全是打包那一档的东西。
//!
//! 拆成 lib 之后,**安全关键的那两部分现在就能编译、能测**:
//! 钥匙串是这一版唯一碰长效凭据的代码,允许清单是唯一决定「壳能访问什么」的代码。
//! 它们不该等到打包那两周才第一次跑起来。

pub mod allowlist;
pub mod keychain;
