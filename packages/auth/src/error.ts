/**
 * 认证失败。
 *
 * ⚠️ **本类刻意不携带失败原因。** 没有 `code`、没有 `reason`、没有 `cause`,
 * 消息也是固定的一句。调用方**不得**对失败原因做分支处理 —— 因为它拿不到,
 * 这是设计,不是遗漏。
 *
 * 理由是认证接口天然是一个预言机(oracle)。一旦区分「token 不存在」/
 * 「token 已过期」/「token 属于另一个租户」/「主体已停用」,攻击者就能用
 * 失败原因当探针:先枚举出哪些 token 真实存在,再针对性攻击。这类信息泄漏
 * 不需要拿到任何有效凭据就能利用,而修复它意味着改变所有调用方的错误处理 ——
 * 所以必须从第一天就封死。
 *
 * **诊断信息去哪了?** 去日志与审计(`@dshwar/audit`,V0.3.0)。
 * 运维需要知道「为什么失败」,调用方不需要 —— 这两条路径必须分开:
 * 一条朝内、可详尽,一条朝外、必须沉默。
 *
 * 实现方(`auth-static` / 将来的 `auth-jwt` / `auth-oidc`)在抛出本错误**之前**
 * 自行记录详细原因,但绝不把它放进错误对象。
 */
export class AuthError extends Error {
  override readonly name = 'AuthError'

  /**
   * 构造一个不含任何原因信息的认证失败。
   *
   * 刻意不接受参数 —— 留一个 `message` 形参,下一个人就会往里塞
   * "token expired"。要让错误的用法写不出来,而不是靠约定。
   */
  constructor() {
    super('authentication failed')
  }
}
